// Generates src/tokens.css: one CSS variable per colour used in the source, with a light value (the design's hex) and a dark value.
// The Vite plugin in vite.config.ts rewrites every "#rrggbb" in src to var(--c-rrggbb), so the design's hex values stay readable in the code.
// Run after adding a colour:  node scripts/gen-tokens.mjs   (test/tokens.test.ts fails if a colour has no token).
import fs from "node:fs"; import path from "node:path";

const DARK = {
  "#ffffff": "#0b0b0c", "#fafafa": "#111113", "#f4f4f5": "#1b1b1e", "#ebebeb": "#27272b", "#d4d4d8": "#4a4a52", "#8a8a8a": "#6e6e76",
  "#111111": "#f4f4f5", "#333333": "#d4d4d8", "#6b6b6b": "#a1a1aa", "#a1a1aa": "#a1a1aa",
  "#0f766e": "#17a596", "#115e59": "#22b8a8", "#f0fdfa": "#0e2a27", "#ccebe7": "#134e4a", "#5eead4": "#5eead4",
  "#caface": "#0f2e18", "#0e7a2f": "#6ee7a0", "#15b042": "#22c55e",
  "#fff1d6": "#3a2a0b", "#8a4b00": "#fbbf24", "#f5d9a8": "#5a4210",
  "#ffe8e6": "#3b1411", "#b42318": "#f87171", "#d92d20": "#ef4444",
  "#e6f0ff": "#0f2238", "#0058b0": "#60a5fa", "#b3d4ff": "#1e3a5f",
  "#1c1c1c": "#1c1c1c", "#2b2b2b": "#2b2b2b",
  // Split-bar colours are FIXED in both themes (the design says they never change): these are visually identical twins of
  // #111111 / #0f766e / #d4d4d8 / #ffffff used only for the merchant / distributor / fee segments and the text on them.
  "#111112": "#111112", "#0f766f": "#0f766f", "#d4d4d9": "#d4d4d9", "#fffffe": "#fffffe",
};
const root = path.resolve(import.meta.dirname, "../src");
const found = new Set();
const walk = (d) => { for (const f of fs.readdirSync(d, { withFileTypes: true })) { const p = path.join(d, f.name); if (f.isDirectory()) walk(p); else if (/\.(tsx?|css)$/.test(f.name) && f.name !== "tokens.css") for (const m of fs.readFileSync(p, "utf8").matchAll(/#([0-9a-fA-F]{6})\b/g)) found.add("#" + m[1].toLowerCase()); } };
walk(root);
const missing = [...found].filter((h) => !DARK[h]);
if (missing.length) { console.error("no dark value for:", missing.join(", ")); process.exit(1); }
const vars = (get) => [...found].sort().map((h) => `  --c-${h.slice(1)}: ${get(h)};`).join("\n");
fs.writeFileSync(path.join(root, "tokens.css"), `/* GENERATED by scripts/gen-tokens.mjs. Do not edit. */
:root { color-scheme: light;\n${vars((h) => h)}
  --glass: rgba(255,255,255,0.86); --glass-2: rgba(250,250,250,0.86); --glass-docs: rgba(255,255,255,0.9);
}
:root[data-theme="dark"] { color-scheme: dark;\n${vars((h) => DARK[h])}
  --glass: rgba(11,11,12,0.82); --glass-2: rgba(17,17,19,0.82); --glass-docs: rgba(11,11,12,0.86);
}
`);
console.log(`tokens.css: ${found.size} colours`);
