import express from "express";
import type { PublicKey } from "@solana/web3.js";
import { BRAND } from "@noux/core";
import { createNouxGateway, type NouxGatewayConfig, type RouteSpec } from "@noux/gateway";

export const SAMPLE_NOTICE = "SAMPLE DATA generated by the Noux demo service. Not real market data. Not financial advice.";

/** Two clearly-labelled sample paid endpoints. Prices are in base units of the campaign mint (6 decimals => 100000 = $0.10). */
export const ROUTES: Record<string, RouteSpec & { display: string }> = {
  "GET /sample/brief": { price: 100_000n, display: "$0.10", description: "Sample daily brief (demo data)" },
  "GET /sample/quote": { price: 30_000n, display: "$0.03", description: "Sample price quote (demo data)" },
};

// deterministic pseudo-data so repeated calls on the same day agree; clearly NOT real
const seeded = (s: string) => { let h = 2166136261; for (const c of s) h = Math.imul(h ^ c.charCodeAt(0), 16777619); return (h >>> 0) / 2 ** 32; };

export interface DemoAppConfig {
  gateway: Omit<NouxGatewayConfig, "routes">;
  claimsApiUrl: string; publicUrl?: string; cluster: string; campaign: PublicKey; mint: PublicKey; merchantPayTo: PublicKey; network: string;
  now?: () => Date;
}

export function createDemoApp(cfg: DemoAppConfig) {
  const now = cfg.now ?? (() => new Date());
  const gw = createNouxGateway({ ...cfg.gateway, routes: Object.fromEntries(Object.entries(ROUTES).map(([k, v]) => [k, { price: v.price, description: v.description }])) });
  const app = express();
  app.disable("x-powered-by");
  app.use((_req, res, next) => { res.setHeader("x-content-type-options", "nosniff"); res.setHeader("access-control-allow-origin", "*"); res.setHeader("access-control-expose-headers", "payment-required, payment-response"); res.setHeader("access-control-allow-headers", `content-type, payment-signature, ${BRAND.claimHeader}`); next(); });
  app.options("*splat", (_q, r) => { r.status(204).end(); });

  // ---- free endpoints
  app.get("/healthz", (_q, r) => { r.json({ ok: true, service: "noux-demo-merchant", sample: true, cluster: cfg.cluster }); });
  app.get("/v1/info", (_q, r) => {
    r.json({
      sample: true, notice: SAMPLE_NOTICE, cluster: cfg.cluster, network: cfg.network, mint: cfg.mint.toBase58(), decimals: 6,
      campaign: cfg.campaign.toBase58(), merchantPayTo: cfg.merchantPayTo.toBase58(), programId: cfg.gateway.programId.toBase58(),
      routes: Object.entries(ROUTES).map(([k, v]) => ({ route: k, price: v.price.toString(), displayPrice: v.display, description: v.description })),
      claims: { api: `${cfg.claimsApiUrl}/v1/claims`, header: BRAND.claimHeader, note: "Request a buyer-signed claim, send it in this header. Without a valid claim the call is a plain purchase: the merchant is paid in full and no commission is created." },
      directory: `${cfg.claimsApiUrl}/v1/campaigns`, receipts: `${cfg.claimsApiUrl}/v1/receipts`,
    });
  });
  app.get("/", (req, r) => {
    if (req.accepts(["html", "json"]) === "json") { r.redirect("/v1/info"); return; }
    r.type("html").send(`<!doctype html><meta charset="utf-8"><title>Noux sample merchant</title><body style="font:16px system-ui;max-width:42rem;margin:3rem auto;padding:0 1rem">
<h1>Noux sample merchant</h1><p><strong>SAMPLE SERVICE.</strong> Built by the Noux team to demonstrate paid x402 calls with referral commissions. The data it returns is generated, not real.</p>
<ul><li><code>GET /sample/brief</code> &mdash; $0.10</li><li><code>GET /sample/quote</code> &mdash; $0.03</li></ul>
<p>Machine-readable description: <a href="/v1/info">/v1/info</a>. Request a claim from <code>${cfg.claimsApiUrl}/v1/claims</code>, pay through x402, then see the public receipt at <code>${cfg.claimsApiUrl}/v1/receipts</code>.</p></body>`);
  });

  // ---- paid endpoints (the gateway middleware answers 402 / verifies / settles; handlers only run once payment verified)
  app.use(gw.middleware);
  app.get("/sample/brief", (_q, r) => {
    const day = now().toISOString().slice(0, 10);
    r.json({ sample: true, notice: SAMPLE_NOTICE, date: day, headline: "Sample brief: markets were calm (generated)", sentiment: Number((seeded(day) * 2 - 1).toFixed(3)), items: ["generated item A", "generated item B", "generated item C"] });
  });
  app.get("/sample/quote", (req, r) => {
    const sym = String(req.query.symbol ?? "SOL").toUpperCase().replace(/[^A-Z0-9]/g, "").slice(0, 10) || "SOL";
    const day = now().toISOString().slice(0, 10);
    r.json({ sample: true, notice: SAMPLE_NOTICE, symbol: sym, date: day, price: Number((20 + seeded(sym + day) * 180).toFixed(2)), currency: "USD" });
  });
  return { app, gateway: gw };
}
